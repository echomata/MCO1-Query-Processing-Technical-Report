INSERT IGNORE INTO dim_date
  (date_sk, full_date, year, quarter, month, month_name, day, day_of_week,
   day_name, week_of_year, is_weekend)
SELECT
  CAST(DATE_FORMAT(g.day_date, '%Y%m%d') AS UNSIGNED),
  g.day_date,
  YEAR(g.day_date),
  QUARTER(g.day_date),
  MONTH(g.day_date),
  MONTHNAME(g.day_date),
  DAY(g.day_date),
  DAYOFWEEK(g.day_date),
  DAYNAME(g.day_date),
  CAST(DATE_FORMAT(g.day_date, '%v') AS UNSIGNED),
  DAYOFWEEK(g.day_date) IN (1, 7)
FROM (
  WITH RECURSIVE d(day_date) AS (
    SELECT CAST('2024-01-01' AS DATE)
    UNION ALL
    SELECT day_date + INTERVAL 1 DAY FROM d
    WHERE day_date < CAST('2026-12-31' AS DATE)
  )
  SELECT day_date FROM d
) AS g;

