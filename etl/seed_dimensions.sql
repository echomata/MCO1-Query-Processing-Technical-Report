  (SELECT COUNT(*) FROM dim_vendor   WHERE vendor_sk   = 0)  AS vendor_unknown_ok,
  (SELECT COUNT(*) FROM dim_payment  WHERE payment_sk  = -1) AS payment_unknown_ok,
  (SELECT COUNT(*) FROM dim_ratecode WHERE ratecode_sk = -1) AS ratecode_unknown_ok,
